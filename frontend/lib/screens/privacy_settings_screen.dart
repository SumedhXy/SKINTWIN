// ─── Location Permission Status Card ───────────────────────────────────────────

class _LocationStatusCard extends StatefulWidget {
  @override
  State<_LocationStatusCard> createState() => _LocationStatusCardState();
}

class _LocationStatusCardState extends State<_LocationStatusCard> {
  LocationPermission _permission = LocationPermission.denied;
  bool _loaded = false;

  @override
  void initState() {
    super.initState();
    _checkPermission();
  }

  Future<void> _checkPermission() async {
    final perm = await Geolocator.checkPermission();
    if (mounted) setState(() { _permission = perm; _loaded = true; });
  }

  @override
  Widget build(BuildContext context) {
    if (!_loaded) return const SizedBox.shrink();

    final (label, color) = switch (_permission) {
      LocationPermission.always => ('Always — Consider changing to While In Use', const Color(0xFFB45309)),
      LocationPermission.whileInUse => ('While In Use', const Color(0xFF16A34A)),
      LocationPermission.denied => ('Denied — Find Care will use manual entry', const Color(0xFF6B7280)),
      LocationPermission.deniedForever => ('Denied Permanently — Open Settings to change', const Color(0xFFDC2626)),
      _ => ('Unknown', const Color(0xFF6B7280)),
    };

    return Container(
      padding: const EdgeInsets.all(14),
      decoration: BoxDecoration(
        color: color.withValues(alpha: 0.06),
        borderRadius: BorderRadius.circular(12),
        border: Border.all(color: color.withValues(alpha: 0.3)),
      ),
      child: Row(
        children: [
          Icon(Icons.my_location_outlined, color: color, size: 18),
          const SizedBox(width: 10),
          Expanded(
            child: Column(
              crossAxisAlignment: CrossAxisAlignment.start,
              children: [
                Text(
                  'Location Permission',
                  style: GoogleFonts.inter(fontWeight: FontWeight.w600, fontSize: 13),
                ),
                const SizedBox(height: 2),
                Text(label, style: GoogleFonts.inter(fontSize: 12, color: color)),
              ],
            ),
          ),
          IconButton(
            icon: const Icon(Icons.refresh, size: 18),
            onPressed: _checkPermission,
            tooltip: 'Refresh',
          ),
        ],
      ),
    );
  }
}
