        'Sharing permissions exist in the data model but sharing features are not yet implemented in the UI.',
        'This system has not undergone a formal third-party security audit.',
      ];

  Future<void> _exportData(BuildContext context) async {
    final account = context.read<AccountProvider>();
    final export = await account.exportData();

    if (!context.mounted) return;

    if (export != null) {
      showDialog(
        context: context,
        builder: (_) => AlertDialog(
          title: Text('Data Export', style: GoogleFonts.outfit(fontWeight: FontWeight.bold)),
          content: Column(
            mainAxisSize: MainAxisSize.min,
            crossAxisAlignment: CrossAxisAlignment.start,
            children: [
              Text(
                'Export summary as of ${_formatDate(export.exportedAt)}:',
                style: GoogleFonts.inter(fontSize: 13, color: AppTheme.textMuted),
              ),
              const SizedBox(height: 12),
              _exportRow('SkinTwins', '${export.totalSkinTwins}'),
              _exportRow('Captures', '${export.totalCaptures}'),
              const SizedBox(height: 12),
              Container(
                padding: const EdgeInsets.all(10),
                decoration: BoxDecoration(
                  color: const Color(0xFFF0FDF4),
                  borderRadius: BorderRadius.circular(8),
                ),
                child: Text(
                  export.exportNotes.first,
                  style: GoogleFonts.inter(fontSize: 12, color: const Color(0xFF166534)),
                ),
              ),
            ],
          ),
          actions: [
            TextButton(
              onPressed: () => Navigator.pop(context),
              child: const Text('Close'),
            ),
          ],
        ),
      );
    } else if (account.errorMessage != null) {
      ScaffoldMessenger.of(context).showSnackBar(
        SnackBar(content: Text(account.errorMessage!)),
      );
    }
  }

  Widget _exportRow(String label, String value) {
    return Padding(
      padding: const EdgeInsets.only(bottom: 4),
      child: Row(
        mainAxisAlignment: MainAxisAlignment.spaceBetween,
        children: [
          Text(label, style: GoogleFonts.inter(fontSize: 14)),
          Text(value,
              style: GoogleFonts.inter(fontWeight: FontWeight.bold, fontSize: 14)),
        ],
      ),
    );
  }

  String _formatDate(DateTime dt) {
    return '${dt.year}-${dt.month.toString().padLeft(2, '0')}-${dt.day.toString().padLeft(2, '0')} '
        '${dt.hour.toString().padLeft(2, '0')}:${dt.minute.toString().padLeft(2, '0')} UTC';
  }

